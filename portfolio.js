function projectPage(left = projectViewport.scrollLeft) {
  return Array.from({ length: projectPageCount() }, (_, page) => projectPageLeft(page))
    .reduce((closest, pageLeft, page) => Math.abs(left - pageLeft) < Math.abs(left - projectPageLeft(closest)) ? page : closest, 0);
}

function scrollToProjectPage(page) {
  const left = projectPageLeft(page);
  const start = projectViewport.scrollLeft;
  const distance = left - start;
  cancelAnimationFrame(scrollToProjectPage.motionFrame);
  clearTimeout(scrollToProjectPage.releaseTimer);
  projectViewport.classList.add("is-settling");

  const finish = () => {
    projectViewport.scrollLeft = left;
    updateProjectScrollbar();
    updateProjectNavigation();
    updateProjectDots();
    requestAnimationFrame(() => projectViewport.classList.remove("is-settling"));
  };

  if (Math.abs(distance) < 1 || matchMedia("(prefers-reduced-motion: reduce)").matches) {
    finish();
    return;
  }

  const startedAt = performance.now();
  const duration = 520;
  const step = (now) => {
    const progress = Math.min((now - startedAt) / duration, 1);
    projectViewport.scrollLeft = start + distance * (1 - Math.pow(1 - progress, 3));
    if (progress < 1) {
      scrollToProjectPage.motionFrame = requestAnimationFrame(step);
      return;
    }
    finish();
  };
  scrollToProjectPage.motionFrame = requestAnimationFrame(step);
}

