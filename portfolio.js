function enableMouseDrag(viewport, onRelease, blockedSelector) {
  let dragging = false;
  let dragged = false;
  let dragStartX = 0;
  let dragScrollLeft = 0;

  viewport.addEventListener("pointerdown", (event) => {
    if (event.pointerType !== "mouse" || event.button !== 0) return;
    if (blockedSelector && event.target.closest(blockedSelector)) return;
    dragging = true;
    dragged = false;
    dragStartX = event.clientX;
    dragScrollLeft = viewport.scrollLeft;
  });
  viewport.addEventListener("pointermove", (event) => {
    if (!dragging) return;
    const distance = event.clientX - dragStartX;
    if (!dragged && Math.abs(distance) > 4) {
      dragged = true;
      viewport.setPointerCapture(event.pointerId);
      viewport.classList.add("is-dragging");
      if (viewport.contains(document.activeElement)) document.activeElement.blur();
    }
    viewport.scrollLeft = dragScrollLeft - distance;
  });
  ["pointerup", "pointercancel"].forEach((eventName) => viewport.addEventListener(eventName, (event) => {
    if (!dragging) return;
    dragging = false;
    if (dragged) onRelease?.(event.clientX - dragStartX, dragScrollLeft);
    viewport.classList.remove("is-dragging");
    if (viewport.hasPointerCapture(event.pointerId)) viewport.releasePointerCapture(event.pointerId);
  }));
  viewport.addEventListener("click", (event) => {
    if (!dragged) return;
    event.preventDefault();
    event.stopPropagation();
    dragged = false;
  }, true);
  viewport.addEventListener("dragstart", (event) => event.preventDefault());
}

