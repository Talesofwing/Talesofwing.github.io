function layoutProjectCards() {
  const cols = projectColumnsPerPage();
  const pageSize = projectPageSize();
  projectCards.forEach((card, index) => {
    const pageIndex = index % pageSize;
    card.style.gridRow = String(Math.floor(pageIndex / cols) + 1);
    card.style.gridColumn = Math.floor(index / pageSize) * cols + (pageIndex % cols) + 1;
  });
}

function projectPageCount() {
  return Math.max(1, Math.ceil(projectCards.length / projectPageSize()));
}

function projectPageLeft(page) {
  const normalizedPage = Math.min(Math.max(page, 0), projectPageCount() - 1);
  if (normalizedPage === 0) return 0;
  const card = projectCards[normalizedPage * projectPageSize()];
  if (!card) return 0;
  const paddingLeft = Number.parseFloat(getComputedStyle(projectViewport).paddingLeft) || 0;
  const left = projectViewport.scrollLeft
    + card.getBoundingClientRect().left
    - projectViewport.getBoundingClientRect().left
    - paddingLeft;
  const maximum = Math.max(0, projectViewport.scrollWidth - projectViewport.clientWidth);
  return Math.max(0, Math.min(Math.round(left), maximum));
}

